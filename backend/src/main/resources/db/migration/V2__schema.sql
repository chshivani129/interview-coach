CREATE TABLE job_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    raw_jd TEXT NOT NULL,
    extracted_skills TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_profile_id BIGINT NOT NULL REFERENCES job_profile(id),
    text TEXT NOT NULL,
    category VARCHAR(50) NOT NULL,
    skill VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES question(id),
    answer_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL UNIQUE REFERENCES attempt(id),

    clarity INTEGER NOT NULL CHECK (clarity BETWEEN 1 AND 5),
    specificity INTEGER NOT NULL CHECK (specificity BETWEEN 1 AND 5),
    depth INTEGER NOT NULL CHECK (depth BETWEEN 1 AND 5),

    feedback TEXT NOT NULL,
    improvement_tip TEXT NOT NULL,

    model VARCHAR(100),
    latency_ms BIGINT,
    tokens_in INTEGER,
    tokens_out INTEGER,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_question_skill ON question(skill);
CREATE INDEX idx_question_job_profile ON question(job_profile_id);
CREATE INDEX idx_attempt_question ON attempt(question_id);